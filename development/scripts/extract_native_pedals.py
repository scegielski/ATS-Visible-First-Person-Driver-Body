"""Extract pedal-only rotation deltas from the validated legacy clip."""
from pathlib import Path
import struct,zipfile,math
root=Path(__file__).resolve().parents[2]
with zipfile.ZipFile(root/'releases/ATS-VisibleDriverBody-Mustang-0.6.1-pedal-alignment-test.scs') as z:
 data=z.read('model/spf_stock_driver/steering_all_pedals.pma')
frames,count=struct.unpack_from('<2I',data,4);offset=struct.unpack_from('<I',data,72)[0]
assert frames==35109 and count==61
def q(frame,bone):return struct.unpack_from('<4f',data,offset+(frame*count+bone)*56+16)
def mul(a,b):
 w,x,y,z=a;v,i,j,k=b
 return (w*v-x*i-y*j-z*k,w*i+x*v+y*k-z*j,w*j-x*k+y*v+z*i,w*k+x*j-y*i+z*v)
def delta(frame,bone):
 base=q(0,bone);v=mul((base[0],-base[1],-base[2],-base[3]),q(frame,bone));n=math.sqrt(sum(x*x for x in v));return tuple(x/n for x in v)
def fmt(v):return '{'+','.join(format(x,'.9f')+'f' for x in v)+'}'
text='// Generated by development/scripts/extract_native_pedals.py from the validated pedal clip.\n#pragma once\n#include "RuntimeArmIK.hpp"\n'
text+='inline constexpr unsigned NativePedalBones[]{54,55,57,51};\n'
for name,indices in [('NativeRightPedals',[i*47 for i in range(83)]),('NativeClutchPedals',[i*3901 for i in range(9)])]:
 text+='inline constexpr DriverIK::Q '+name+'[][4]={\n'
 text+='\n'.join(' {'+','.join(fmt(delta(f,b)) for b in [54,55,57,51])+'},' for f in indices)+'\n};\n'
(root/'native-diagnostics/NativePedalSamples.hpp').write_text(text)

